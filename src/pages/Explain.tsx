/**
 * /explain — marketing-pivot page. Click → real chess explanation.
 *
 * Phase 3.2 (this file): hero board + CTA + result + demo grid + a
 * paste-your-own-position input (FEN or Lichess analysis/editor URL).
 *
 * Architecture: the page is a thin shell around `useExplainPosition`
 * (which lifts the cache-check + POST flow from GameAnalysisWrapper)
 * and `PositionExplanationCard` (which renders the structured result).
 * No bespoke renderer, no duplicated cache logic.
 */

import { useRef, useState } from 'react';
import { Lightbulb } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { ChessBoard } from '@/components/chess/ChessBoard';
import { PositionExplanationCard } from '@/components/game-analysis/PositionExplanationCard';
import { positionFromFen } from '@/components/chess/chessLogic';
import {
  useExplainPosition,
  type PositionExplanation,
  type ExplainOutcome,
} from '@/features/explain/useExplainPosition';
import { useIsMobile } from '@/hooks/use-mobile';
import { logGA4Event } from '@/services/analytics';
import type { StructuredExplanation } from '@/types/positionExplanation';
import demoPositions from '@/features/explain/demo-positions.json';
import demoExplanations from '@/features/explain/demo-explanations.json';
import SeoHead from '@/components/SeoHead';

interface DemoPosition {
  id: string;
  title: string;
  subtitle: string;
  fen: string;
  lastMoveClassification: string;
}

const DEMOS = demoPositions as DemoPosition[];
const HERO = DEMOS[0]; // Rotlewi–Rubinstein 1907

// Statically-baked demo explanations (generated by
// backend/scripts/bake-demo-explanations.ts at the current PIPELINE_VERSION).
// Seeded into the explain hook's cache so the 6 curated positions render
// in <100ms with no network round-trip.
const BAKED_EXPLANATIONS = demoExplanations.byFen as Record<string, PositionExplanation>;

/**
 * Accept either a raw FEN or a Lichess analysis/editor URL and return the
 * FEN plus which source it came from (for the analytics event).
 *
 * Per the no-Lichess-API rule, we only read FENs the URL already carries
 * (`?fen=`, `/analysis/<fen>`, `/editor/<fen>`) — never fetch a game by id.
 * Lichess encodes spaces in path FENs as underscores.
 */
function extractPosition(raw: string): { fen: string; source: 'fen' | 'lichess_url' } | null {
  const trimmed = raw.trim();
  if (!trimmed) return null;

  if (/lichess\.org/i.test(trimmed)) {
    try {
      const url = new URL(trimmed.startsWith('http') ? trimmed : `https://${trimmed}`);
      const q = url.searchParams.get('fen');
      if (q) return { fen: q.replace(/_/g, ' ').trim(), source: 'lichess_url' };
      const m = url.pathname.match(/\/(?:analysis|editor)\/(?:standard\/|fromPosition\/)?(.+)$/);
      if (m && m[1]) {
        return { fen: decodeURIComponent(m[1]).replace(/_/g, ' ').trim(), source: 'lichess_url' };
      }
    } catch {
      /* not a parseable URL — fall through */
    }
    return null; // a Lichess link we can't read a FEN from (e.g. a game id)
  }

  return { fen: trimmed, source: 'fen' };
}

/**
 * Compact "payoff" preview shown above the fold before the user clicks —
 * the position's verdict + the one move that matters, in the same language
 * as the full Coach's Briefing card. Renders NO chess text of its own: both
 * strings are backend-sourced (here, from the statically-baked explanation).
 */
function PayoffTeaser({ structured, className = '' }: { structured: StructuredExplanation; className?: string }) {
  return (
    <div className={`rounded-xl border border-border bg-card overflow-hidden ${className}`}>
      <div className="px-4 py-3 border-b border-border">
        <p className="font-serif text-lg leading-tight text-foreground">{structured.verdict.eval}</p>
        {structured.verdict.reason && <p className="mt-1 text-sm text-muted-foreground">{structured.verdict.reason}</p>}
      </div>
      {structured.action && (
        <div className="m-3 rounded-lg p-3 bg-inverse text-inverse-foreground">
          <div className="flex items-center gap-1.5 text-[10px] font-bold uppercase tracking-widest text-inverse-accent">
            <Lightbulb className="h-3 w-3" aria-hidden />
            What matters now
          </div>
          <p className="mt-1 font-serif text-sm leading-snug">{structured.action}</p>
        </div>
      )}
    </div>
  );
}

export default function Explain() {
  const [fen, setFen] = useState<string>(HERO.fen);
  const [activeDemo, setActiveDemo] = useState<DemoPosition | null>(HERO);
  const [customCaption, setCustomCaption] = useState<string | null>(null);
  const [inputValue, setInputValue] = useState('');
  const [inputError, setInputError] = useState<string | null>(null);
  const { explanation, loading, error, depth, explain } = useExplainPosition(BAKED_EXPLANATIONS);
  const isMobile = useIsMobile();

  const captionTitle = activeDemo ? activeDemo.title : 'Your position';
  const captionSubtitle = activeDemo ? activeDemo.subtitle : (customCaption ?? '');

  // Pre-click payoff preview: the current position's baked verdict/action, so
  // the value proposition is visible above the fold with no network round-trip.
  // Present only for the (baked) demo positions; a custom paste shows it after
  // the live explanation returns.
  const heroStructured: StructuredExplanation | null = BAKED_EXPLANATIONS[fen]?.structured ?? null;

  // Scroll to the very top, not to the board — scrolling the board to `block:
  // 'start'` crops the hero copy above it, so a visitor who picked a demo from
  // the grid below lands mid-page with no framing for what they are looking at.
  // Going to the top keeps the H1 AND the board+briefing in frame at every
  // width.
  //
  // Deferred to after the intro→result layout swap commits: scrolling in the
  // same tick as setFen/explain runs against the about-to-reflow DOM, which
  // lands wrong or gets stomped and the page appears to stay put. Two rAFs wait
  // for the new layout.
  const scrollToTop = () =>
    requestAnimationFrame(() =>
      requestAnimationFrame(() => window.scrollTo({ top: 0, behavior: 'smooth' }))
    );

  // ── Delivery instrumentation (D3) ──────────────────────────────────────
  // The `explain_position_*` events below fire on click, before the network
  // round-trip, so they count intent: a visitor whose engine never became ready
  // still registers. They remain in place because Google Ads conversion actions
  // depend on them, and `explain_delivered` runs in parallel until that account
  // change is made.
  //
  // Distinct FENs, not call count — re-explaining the same position must not
  // look like exploring a second one. `position_index >= 2` is the
  // second-position signal.
  const deliveredFens = useRef<Set<string>>(new Set());

  const recordOutcome = (
    fen: string,
    source: 'demo' | 'custom',
    demoId: string | undefined,
    outcome: ExplainOutcome,
  ) => {
    // `=== false`, not `!outcome.ok`. tsconfig.app.json sets "strict": false, and
    // without strictNullChecks TypeScript will not narrow a discriminated union
    // through a truthiness test — only through an explicit literal comparison.
    // Written as `!outcome.ok` this fails to compile with "Property 'reason'
    // does not exist on type ExplainOutcome", which is what it was doing.
    if (outcome.ok === false) {
      logGA4Event({ name: 'explain_failed', params: { source, reason: outcome.reason } });
      return;
    }
    deliveredFens.current.add(fen);
    logGA4Event({
      name: 'explain_delivered',
      params: {
        source,
        ...(demoId ? { demo_id: demoId } : {}),
        cached: outcome.cached,
        position_index: deliveredFens.current.size,
      },
    });
  };

  // Load a demo onto the hero board and explain it in one action. `explain`
  // manages its own loading/error/cache state, so there is no separate reset
  // to race against — the previous result is replaced (instantly when the
  // demo is cached, via the loading state otherwise).
  const selectDemo = (demo: DemoPosition) => {
    setActiveDemo(demo);
    setCustomCaption(null);
    setFen(demo.fen);
    logGA4Event({
      name: 'explain_position_demo',
      params: { demo_id: demo.id, demo_slug: demo.id },
    });
    void explain(demo.fen).then((o) => recordOutcome(demo.fen, 'demo', demo.id, o));
    scrollToTop();
  };

  // Hero CTA — explains whatever is currently loaded, firing the event that
  // matches its source (a demo card, or a pasted custom position).
  const handleExplain = () => {
    if (activeDemo) {
      logGA4Event({
        name: 'explain_position_demo',
        params: { demo_id: activeDemo.id, demo_slug: activeDemo.id },
      });
    } else {
      logGA4Event({ name: 'explain_position_custom', params: { source: 'fen' } });
    }
    void explain(fen).then((o) =>
      recordOutcome(fen, activeDemo ? 'demo' : 'custom', activeDemo?.id, o),
    );
  };

  const handleCustomSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setInputError(null);
    const parsed = extractPosition(inputValue);
    if (!parsed) {
      setInputError('Paste a FEN, or a Lichess analysis/editor link. Game links aren’t supported yet.');
      return;
    }
    if (!positionFromFen(parsed.fen)) {
      setInputError('That doesn’t look like a legal position. Check the FEN and try again.');
      return;
    }
    setActiveDemo(null);
    setCustomCaption(parsed.source === 'lichess_url' ? 'From your Lichess link' : 'Your pasted position');
    setFen(parsed.fen);
    logGA4Event({ name: 'explain_position_custom', params: { source: parsed.source } });
    void explain(parsed.fen).then((o) => recordOutcome(parsed.fen, 'custom', undefined, o));
    scrollToTop();
  };

  return (
    <>
      <SeoHead routeKey="explain" />

      <div className="bg-background flex flex-col">

        <main className="flex-grow">
          {/* Hero — Concept D: a decisive 5/7 split, the payoff visible above the fold */}
          <section
            className="relative px-4 sm:px-6 lg:px-8 pt-5 sm:pt-6 lg:pt-10 pb-8 lg:pb-10 max-w-6xl mx-auto w-full scroll-mt-20"
          >
            {/* soft gold glow behind the board — the page's one warm accent */}
            <div
              aria-hidden
              className="pointer-events-none absolute right-2 top-4 h-[360px] w-[360px] rounded-full bg-primary/10 blur-[80px]"
            />

            {explanation || loading || error ? (
              /* Result — board (left) + the full Coach's Briefing (right). The
                 marketing copy steps aside once the user has engaged; the demo
                 grid below lets them try another. */
              <div className="relative grid grid-cols-1 lg:grid-cols-[minmax(0,360px)_1fr] gap-6 lg:gap-8 items-start">
                <div className="w-full max-w-md mx-auto lg:mx-0">
                  <div className="aspect-square rounded-lg overflow-hidden">
                    <ChessBoard fen={fen} orientation="white" viewOnly coordinates />
                  </div>
                  <div className="mt-3 flex items-baseline gap-2 border-t border-border pt-2 min-w-0">
                    <span
                      className="text-sm text-foreground whitespace-nowrap"
                      style={{ fontVariant: 'small-caps', letterSpacing: '0.04em' }}
                    >
                      {captionTitle}
                    </span>
                    {captionSubtitle && (
                      <span className="text-xs text-muted-foreground truncate">{captionSubtitle}</span>
                    )}
                  </div>
                </div>
                <div className="min-w-0">
                  <PositionExplanationCard
                    structured={explanation?.structured ?? null}
                    loading={loading}
                    error={error}
                    loadingDepth={depth}
                    isMobile={isMobile}
                  />
                </div>
              </div>
            ) : (
              /* Intro — decisive 5/7 split with the payoff teaser above the fold */
              <>
                <div className="relative grid grid-cols-1 lg:grid-cols-[5fr_7fr] gap-8 lg:gap-12 items-center">
                  {/* Copy — reads first on desktop */}
                  <div className="min-w-0 text-center lg:text-left">
                    <span className="text-[11px] font-bold uppercase tracking-[0.18em] text-link">
                      The Position Explainer
                    </span>
                    <h1 className="font-serif text-4xl sm:text-5xl lg:text-[3.25rem] leading-[1.02] text-foreground mt-3">
                      See <span className="text-link">why</span> the position works.
                    </h1>
                    <p className="text-base sm:text-lg text-muted-foreground mt-4 max-w-md mx-auto lg:mx-0">
                      Engine numbers say <span className="italic">who&rsquo;s</span> better. We say why —
                      the plans, the threats, and the one move that matters.
                    </p>
                    <div className="mt-6">
                      <Button onClick={handleExplain} disabled={loading} size="lg" className="w-full sm:w-auto">
                        {loading ? 'Analyzing position…' : 'Explain this position →'}
                      </Button>
                    </div>
                    <p className="mt-4 text-xs text-muted-foreground">
                      Stockfish-backed
                      <span className="mx-2 text-border">|</span>
                      Any FEN or Lichess link
                      <span className="mx-2 text-border">|</span>
                      No account required
                    </p>
                  </div>

                  {/* Board + its answer — one position, one answer */}
                  <div className="relative min-w-0 mx-auto lg:mx-0 w-full max-w-md lg:max-w-none lg:w-[560px]">
                    <div className="w-full max-w-md mx-auto lg:mx-0 lg:w-[380px]">
                      <div className="aspect-square rounded-lg overflow-hidden">
                        <ChessBoard fen={fen} orientation="white" viewOnly coordinates />
                      </div>
                      {/* annotated game-plate caption */}
                      <div className="mt-3 flex items-baseline gap-2 border-t border-border pt-2">
                        <span
                          className="text-sm text-foreground"
                          style={{ fontVariant: 'small-caps', letterSpacing: '0.04em' }}
                        >
                          {captionTitle}
                        </span>
                        {captionSubtitle && (
                          <span className="text-xs text-muted-foreground truncate">{captionSubtitle}</span>
                        )}
                      </div>
                    </div>

                    {heroStructured ? (
                      <PayoffTeaser
                        structured={heroStructured}
                        className="mt-4 shadow-xl lg:mt-0 lg:absolute lg:right-0 lg:bottom-16 lg:w-[300px] lg:z-10 lg:shadow-2xl"
                      />
                    ) : null}
                  </div>
                </div>

                {/* below-fold nudge (mobile only — desktop lets the demo grid peek) */}
                <p className="mt-8 text-center text-xs text-muted-foreground lg:hidden">
                  6 famous positions below ↓
                </p>
              </>
            )}
          </section>

          {/* Demo grid — the 6 curated positions. */}
          <section className="px-4 sm:px-6 lg:px-8 pb-8 lg:pb-12 max-w-6xl mx-auto w-full">
            <h2 className="text-xl sm:text-2xl font-semibold text-foreground mb-1">
              Try a famous position
            </h2>
            <p className="text-sm text-muted-foreground mb-5">
              Six legendary moments. Tap one to load it on the board and read what's going on.
            </p>

            <div className="grid grid-cols-2 sm:grid-cols-3 gap-3 sm:gap-4">
              {DEMOS.map((demo) => {
                const isActive = demo.id === activeDemo?.id;
                return (
                  <button
                    key={demo.id}
                    type="button"
                    onClick={() => selectDemo(demo)}
                    aria-pressed={isActive}
                    className={
                      'group text-left rounded-lg border bg-card p-2.5 sm:p-3 transition-colors ' +
                      'focus:outline-none focus-visible:ring-2 focus-visible:ring-ring ' +
                      (isActive
                        ? 'border-primary ring-1 ring-primary'
                        : 'border-border hover:border-primary/60')
                    }
                  >
                    <div className="aspect-square rounded overflow-hidden">
                      <ChessBoard fen={demo.fen} orientation="white" viewOnly />
                    </div>
                    <p className="mt-2 text-xs sm:text-sm font-medium text-foreground line-clamp-1">
                      {demo.title}
                    </p>
                    <p className="text-[11px] sm:text-xs text-muted-foreground line-clamp-2">
                      {demo.subtitle}
                    </p>
                  </button>
                );
              })}
            </div>
          </section>

          {/* Paste-your-own position. */}
          <section className="px-4 sm:px-6 lg:px-8 pb-12 lg:pb-16 max-w-6xl mx-auto w-full">
            <div className="rounded-lg border border-border bg-card/40 p-4 sm:p-6">
              <h2 className="text-xl sm:text-2xl font-semibold text-foreground mb-1">
                Explain your own position
              </h2>
              <p className="text-sm text-muted-foreground mb-4">
                Paste a FEN or a Lichess analysis link, and we'll explain it the same way.
              </p>
              <form onSubmit={handleCustomSubmit} className="flex flex-col sm:flex-row gap-2 sm:gap-3">
                <Input
                  value={inputValue}
                  onChange={(e) => setInputValue(e.target.value)}
                  placeholder="rnbqkbnr/pppppppp/8/8/… or https://lichess.org/analysis/…"
                  aria-label="FEN or Lichess link"
                  aria-invalid={inputError ? true : undefined}
                  className="flex-grow font-mono text-xs sm:text-sm"
                />
                <Button type="submit" disabled={loading} className="shrink-0">
                  Explain it →
                </Button>
              </form>
              {inputError && (
                <p className="mt-2 text-xs text-destructive" role="alert">
                  {inputError}
                </p>
              )}
            </div>
          </section>
        </main>

      </div>
    </>
  );
}
